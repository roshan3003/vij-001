# difference between Module, Library and package####################################################################
#MODULE###############################################################################
#A module is a single python file it consists python code.
#It contains functions, classes and variable
#examples of a modules such as math.py,random.py and mymodule.py

#Package################################################################################
#A package is a collection of modules
#it contains __int__.py file
#examples of package numpy,pandas and django.

#LIBRARY##############################################################################
#A library can consist of both modules and packages.
#examples: numpy,pandas and matplotlib

#note: every python file is a module and "import" is a keyword.
#every python file is saved internally with variable names as "__main__".